//! The five snippet types and what each must produce, from `fixtures/compat-expected.toml`.
//!
//! `fixtures/compat.json` holds the same snippets in the library import format; a test
//! imports it and runs the engine's dry run to prove the two agree.

use iamb_core::datetime::{civil_from_days, days_from_civil};
use serde::Deserialize;

/// The expected results, compiled in.
pub const EXPECTED_TOML: &str = include_str!("../../fixtures/compat-expected.toml");
/// The fixture library in the import format, compiled in.
pub const FIXTURE_JSON: &str = include_str!("../../fixtures/compat.json");
/// The fixed date the dry-run tests and `compat-expected.txt` use.
pub const FIXED_DATE: &str = "2026-03-18";
/// The marker typed after an expansion to check where the caret is.
pub const CARET_PROBE: char = '^';

/// One snippet type (T1 to T5).
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SnippetType {
    /// `T1` to `T5`.
    pub id: String,
    /// A short name.
    pub name: String,
    /// What is typed.
    pub abbreviation: String,
    /// The text after the expansion (`{date}` and `{caret}` placeholders).
    pub expected: String,
    /// The text on a one-line field, where it differs.
    #[serde(default)]
    pub single_line: Option<String>,
    /// Rich surfaces are checked for structure.
    #[serde(default)]
    pub rich: bool,
    /// What to look for on a rich surface.
    #[serde(default)]
    pub rich_checks: Vec<String>,
}

#[derive(Deserialize)]
struct File {
    r#type: Vec<SnippetType>,
}

/// The expected text of one expansion and where the caret ends.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Expectation {
    /// The field's text.
    pub text: String,
    /// The caret, in characters from the start of `text`.
    pub caret: usize,
}

impl Expectation {
    /// The text with `marker` inserted at the caret.
    pub fn with_marker(&self, marker: char) -> String {
        let mut out: String = self.text.chars().take(self.caret).collect();
        out.push(marker);
        out.extend(self.text.chars().skip(self.caret));
        out
    }
}

impl SnippetType {
    /// The number 1 to 5.
    pub fn number(&self) -> u8 {
        self.id.trim_start_matches('T').parse().unwrap_or(0)
    }

    /// The expectation for `date` (`YYYY-MM-DD`); a one-line field uses `single_line` text.
    pub fn expectation(&self, date: &str, one_line: bool) -> Expectation {
        let source = match (&self.single_line, one_line) {
            (Some(text), true) => text.as_str(),
            _ => self.expected.as_str(),
        };
        let with_date = source.replace("{date}", date);
        match with_date.split_once("{caret}") {
            Some((before, after)) => Expectation {
                caret: before.chars().count(),
                text: format!("{before}{after}"),
            },
            None => Expectation {
                caret: with_date.chars().count(),
                text: with_date,
            },
        }
    }

    /// True when the text depends on the date.
    pub fn has_date(&self) -> bool {
        self.expected.contains("{date}")
    }
}

/// The five types, in order.
pub fn types() -> Result<Vec<SnippetType>, String> {
    let file: File =
        toml::from_str(EXPECTED_TOML).map_err(|e| format!("compat-expected.toml: {e}"))?;
    Ok(file.r#type)
}

/// The date after `date` (`YYYY-MM-DD`), for a run that crosses midnight.
pub fn next_day(date: &str) -> Option<String> {
    let mut parts = date.split('-');
    let y: i32 = parts.next()?.parse().ok()?;
    let m: u8 = parts.next()?.parse().ok()?;
    let d: u8 = parts.next()?.parse().ok()?;
    if parts.next().is_some() || !(1..=12).contains(&m) || !(1..=31).contains(&d) {
        return None;
    }
    let (y, m, d) = civil_from_days(days_from_civil(y, m, d) + 1);
    Some(format!("{y:04}-{m:02}-{d:02}"))
}

/// The plain-text file with the expected outputs, for a person to compare by eye.
pub fn render_expected_txt(date: &str) -> Result<String, String> {
    use std::fmt::Write as _;

    let mut out = String::new();
    let _ = writeln!(
        out,
        "Expected results of the compatibility snippets (generated by `iamb-compat expected`)."
    );
    let _ = writeln!(
        out,
        "Date used below: {date}. The caret is shown as | and is not part of the text."
    );
    let _ = writeln!(
        out,
        "Every line between the BEGIN and END lines is the field's text; the lines themselves are not."
    );
    for t in types()? {
        let exp = t.expectation(date, false);
        let _ = writeln!(out, "\n{} {} - type {}", t.id, t.name, t.abbreviation);
        let _ = writeln!(
            out,
            "length: {} characters, caret after character {}",
            exp.text.chars().count(),
            exp.caret
        );
        let _ = writeln!(out, "----- BEGIN {} -----", t.id);
        let _ = writeln!(out, "{}", exp.with_marker('|'));
        let _ = writeln!(out, "----- END {} -----", t.id);
        if let Some(one) = &t.single_line {
            let _ = writeln!(out, "on a one-line field (Windows Settings search box):");
            let _ = writeln!(out, "{one}");
        }
        for check in &t.rich_checks {
            let _ = writeln!(out, "rich surface: {check}");
        }
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn five_types_in_order() {
        let t = types().unwrap_or_default();
        let ids: Vec<&str> = t.iter().map(|t| t.id.as_str()).collect();
        assert_eq!(ids, ["T1", "T2", "T3", "T4", "T5"]);
        assert_eq!(t[3].number(), 4);
    }

    #[test]
    fn template_expectation_has_the_caret_at_the_macro() {
        let t4 = &types().unwrap_or_default()[3];
        let e = t4.expectation("2026-03-18", false);
        assert_eq!(e.text, "Report for 2026-03-18:  - done");
        assert_eq!(e.caret, "Report for 2026-03-18: ".chars().count());
        assert_eq!(
            e.with_marker('^'),
            "Report for 2026-03-18: ^ - done".to_owned()
        );
    }

    #[test]
    fn plain_types_have_the_caret_at_the_end() {
        let t1 = &types().unwrap_or_default()[0];
        let e = t1.expectation("2026-03-18", false);
        assert_eq!(e.caret, 27);
        assert_eq!(e.with_marker('^'), "Kind regards, the Iamb team^");
    }

    #[test]
    fn one_line_text_drops_the_newlines() {
        let t2 = &types().unwrap_or_default()[1];
        assert_eq!(
            t2.expectation("2026-03-18", false).text.chars().count(),
            500
        );
        let one = t2.expectation("2026-03-18", true).text;
        assert_eq!(one.chars().count(), 493);
        assert!(!one.contains('\n'));
    }

    #[test]
    fn next_day_rolls_over() {
        assert_eq!(next_day("2026-03-18").as_deref(), Some("2026-03-19"));
        assert_eq!(next_day("2026-12-31").as_deref(), Some("2027-01-01"));
        assert_eq!(next_day("2028-02-28").as_deref(), Some("2028-02-29"));
        assert_eq!(next_day("nonsense"), None);
    }
}
